// Push Method
const frut = ["Banana" , "Apple" , "Mango"] ; //That Add One In Last Value
frut.push("Kiwi");
console.log(frut);

// Pop Method
const fruits = ["Banana", "Orange", "Apple", "Mango"]; // Select In last One Value
let fruit = fruits.pop();
console.log(fruit);

// Shift Method
const frits = ["Banana", "Orange", "Apple", "Mango"];  //Select in First value 
let fruite = frits.shift();
console.log(fruite);


// Unshift Method
const vegtables = ["Banana", "Orange", "Apple", "Mango"]; // Add one in First value
vegtables.unshift("Lemon");
console.log(vegtables);

