//Var Keyword Example
var x = 5;
console.log("Initial value of x:", x); // Output: 5
x = 15;
console.log("Updated value of x:", x); // Output: 15
// Let Keyword Example
let a = 10;
console.log("Initial value of a:", a); // Output: 10
// let a = 40; not allowed
// a = 20;
console.log("Updated value of a:", a); // Output: 20
// Const Keyword Example
const b = 30;
console.log("Value of b:", b); // Output: 30
// b = 40; This will throw an error: TypeError: Assignment to constant variable.
